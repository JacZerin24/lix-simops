"""Render real LightningCast GeoJSON contours with MRMS lowest-level reflectivity.

The input must be *authentic* CSPP Geo LightningCast contours in geographic
GeoJSON, with a selected numeric percent field in each feature's properties.
No probability data are generated by this script. Verify the native schema
and any parallax correction before calling it.
"""
from __future__ import annotations

import argparse
from bisect import bisect_right
from datetime import datetime, timedelta, timezone
import json
from pathlib import Path
import re

from render_common import add_base_map, local_time_label, timestamp_token
from render_mrms import file_time as mrms_file_time, open_grib

SOURCE_TIME_RE = re.compile(r"(20\d{6})[T_-](\d{4})(\d{2})?Z?")
NATIVE_TIME_RE = re.compile(r"_s(20\d{6})(\d{6})\d(?:_|$)")
COLORS = {10: "#1976d2", 25: "#00acc1", 50: "#4caf50", 75: "#bf40bf"}
MRMS_PRODUCT = "MergedReflectivityAtLowestAltitude_00.50"
DOMAIN = (-93.0, -87.0, 27.5, 32.5)


def lightningcast_file_time(path: Path) -> datetime:
    native = NATIVE_TIME_RE.search(path.stem)
    if native is not None:
        date, clock = native.groups()
        return datetime.strptime(date + clock, "%Y%m%d%H%M%S").replace(tzinfo=timezone.utc)
    match = SOURCE_TIME_RE.search(path.stem)
    if match is None:
        raise ValueError(
            "Cannot identify historical scene time in " + path.name +
            "; expected native CSPP _sYYYYMMDDHHMMSSd or YYYYMMDDTHHMMSSZ filename"
        )
    date, clock, seconds = match.groups()
    return datetime.strptime(date + clock + (seconds or "00"), "%Y%m%d%H%M%S").replace(
        tzinfo=timezone.utc
    )


def mrms_before(
    times: list[datetime], lightningcast_time: datetime, max_age: timedelta
) -> int | None:
    """Choose last real MRMS time <= probability scene time; never use future data."""
    index = bisect_right(times, lightningcast_time) - 1
    if index < 0 or (lightningcast_time - times[index]) > max_age:
        return None
    return index


def parse_contours(source: Path, probability_field: str) -> list[tuple[int, dict]]:
    """Return validated features, preserving GeoJSON geometry in WGS84."""
    data = json.loads(source.read_text(encoding="utf-8"))
    if data.get("type") != "FeatureCollection":
        raise ValueError(f"{source}: expected a geographic GeoJSON FeatureCollection")
    result = []
    for feature in data.get("features", []):
        props = feature.get("properties") or {}
        value = props.get(probability_field)
        if value is None:
            raise ValueError(
                f"{source}: GeoJSON missing probability property {probability_field!r}; "
                "inspect the authentic CSPP schema and explicitly select its percent property"
            )
        try:
            level = float(value)
        except (TypeError, ValueError) as exc:
            raise ValueError(f"Invalid probability level {value!r}") from exc
        if not (0 <= level <= 100):
            raise ValueError(f"Probability must be a percent in 0..100, got {level!r}")
        if feature.get("geometry") is None:
            raise ValueError("Missing GeoJSON contour geometry")
        if level in COLORS:
            result.append((int(level), feature["geometry"]))
    if not result:
        raise ValueError(
            f"{source}: no 10/25/50/75% contour features; inspect native model output"
        )
    return result


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--lightningcast", type=Path, required=True,
                        help="Directory containing real geolocated GeoJSON contours")
    parser.add_argument("--mrms", type=Path, required=True,
                        help="Original MRMS lowest-altitude reflectivity GRIB2 files")
    parser.add_argument("--output-root", type=Path, default=Path("data/raw/meso"))
    parser.add_argument("--probability-field", default="PROBABILITY",
                        help="Exact property containing 0..100 probability; verify CSPP output")
    parser.add_argument("--max-mrms-age-minutes", type=float, default=4)
    parser.add_argument("--timezone", default="America/Chicago")
    parser.add_argument("--simulation-date", default="2027-02-06")
    parser.add_argument("--local-time-offset-minutes", type=int, default=825)
    args = parser.parse_args()

    # Scientific dependency checks should only be required at rendering time.
    import cartopy.crs as ccrs
    from matplotlib import pyplot as plt
    from matplotlib.lines import Line2D
    import numpy as np
    from shapely.geometry import shape

    lc_files = sorted([*args.lightningcast.rglob("*.geojson"), *args.lightningcast.rglob("*.json")])
    if not lc_files:
        parser.error("No native LightningCast GeoJSON/.json files found; run CSPP Geo first.")
    mrms_files = sorted(
        p for p in args.mrms.iterdir()
        if p.is_file() and ".grib2" in p.name
    )
    mrms_index = sorted((mrms_file_time(p), p) for p in mrms_files)
    if not mrms_index:
        parser.error("No original MRMS reflectivity GRIB2 files found.")

    mrms_times = [t for t, _ in mrms_index]
    max_age = timedelta(minutes=args.max_mrms_age_minutes)
    rendered = 0
    skipped = 0
    for source in lc_files:
        when = lightningcast_file_time(source)
        idx = mrms_before(mrms_times, when, max_age)
        if idx is None:
            print(f"Skipping {source.name}: no MRMS observation at/before time within {max_age}")
            skipped += 1
            continue
        probability_features = parse_contours(source, args.probability_field)
        mrms_time, mrms_source = mrms_index[idx]

        handle, temp_path = open_grib(mrms_source)
        try:
            message = handle.message(1)
            values = np.asarray(message.values, dtype=float)
            lats, lons = message.latlons()
            lons = np.where(lons > 180, lons - 360, lons)
            west, east, south, north = DOMAIN
            mask = (lons >= west) & (lons <= east) & (lats >= south) & (lats <= north)
            rows, cols = np.where(mask)
            if rows.size == 0:
                raise ValueError("MRMS grid does not intersect specified LIX domain")
            sl = (slice(rows.min(), rows.max()+1), slice(cols.min(), cols.max()+1))
            lats, lons = lats[sl], lons[sl]
            values = np.ma.masked_where(
                (values[sl] <= 5) | ~np.isfinite(values[sl]), values[sl]
            )
        finally:
            handle.close()
            if temp_path is not None:
                temp_path.unlink(missing_ok=True)

        for combined in (False, True):
            fig = plt.figure(figsize=(10, 8), constrained_layout=True)
            ax = plt.axes(projection=ccrs.PlateCarree())
            add_base_map(ax, domain=DOMAIN)
            if combined:
                cmap = plt.get_cmap("turbo").copy()
                cmap.set_bad((1, 1, 1, 0))
                mesh = ax.pcolormesh(
                    lons, lats, values, transform=ccrs.PlateCarree(),
                    cmap=cmap, vmin=0, vmax=75, shading="auto", zorder=2
                )
                cb = fig.colorbar(mesh, ax=ax, orientation="horizontal", pad=0.035, shrink=0.82)
                cb.set_label("MRMS lowest-altitude reflectivity (dBZ)")
            for level, geometry in probability_features:
                geom = shape(geometry)
                if not geom.is_valid:
                    raise ValueError(f"Invalid geographic contour shape in {source.name}")
                ax.add_geometries(
                    [geom], crs=ccrs.PlateCarree(), facecolor="none",
                    edgecolor=COLORS[level], linewidth=2.5, zorder=6
                )
            legend = [
                Line2D([0], [0], color=color, lw=2.5, label=f"{prob}%")
                for prob, color in COLORS.items()
            ]
            ax.legend(handles=legend, loc="lower left", title="LightningCast · next 60 min",
                      ncol=4, fontsize=8)
            ax.set_title(
                "LightningCast + MRMS lowest reflectivity" if combined else "LightningCast Probability",
                loc="left", fontweight="bold"
            )
            ax.set_title(
                local_time_label(
                    when, args.timezone, args.simulation_date,
                    args.local_time_offset_minutes
                ),
                loc="right"
            )
            if combined:
                ax.text(0.99, 0.015, f"MRMS valid {mrms_time:%H:%M} UTC",
                        transform=ax.transAxes, ha="right", va="bottom", fontsize=8)
            kind = "lightningcast_mrms_lowest_refl" if combined else "lightningcast"
            folder = args.output_root / kind
            folder.mkdir(parents=True, exist_ok=True)
            target = folder / f"{kind}_{timestamp_token(when)}.png"
            fig.savefig(target, dpi=130, bbox_inches="tight", facecolor="white")
            plt.close(fig)
            print(f"Rendered {target}")
        rendered += 1
    if not rendered:
        raise SystemExit("No valid time-paired genuine LightningCast/MRMS frame sets.")
    print(f"LightningCast scenes rendered: {rendered}; skipped: {skipped}")


if __name__ == "__main__":
    main()
